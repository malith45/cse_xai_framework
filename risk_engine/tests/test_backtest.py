import numpy as np
import pytest

from cse_risk_engine import rolling_var_backtest, kupiec_pof_test, ConvergenceError

WINDOW = 300  # smaller than 750 to keep the test fast; the logic is identical


@pytest.fixture(scope="module")
def bt(synthetic_returns):
    r = synthetic_returns[:900]
    return rolling_var_backtest(r, window=WINDOW, confidence=(0.95, 0.99), refit_every=50,
                                n_paths=4000, seed=0)


def test_structure(bt, synthetic_returns):
    n = 900
    assert bt.index[0] == WINDOW and bt.index[-1] == n - 1
    assert bt.index.size == n - WINDOW
    assert bt.refit_index.size == int(np.ceil((n - WINDOW) / 50))
    assert bt.failed_fits == ()
    np.testing.assert_array_equal(bt.realised, synthetic_returns[WINDOW:n])
    for c in (0.95, 0.99):
        assert bt.var[c].shape == bt.realised.shape
        assert np.all(bt.var[c] > 0)
        np.testing.assert_array_equal(bt.breaches[c], bt.realised < -bt.var[c])
        assert bt.kupiec[c].as_dict() == kupiec_pof_test(bt.breaches[c], confidence=c).as_dict()
    assert np.all(bt.var[0.99] > bt.var[0.95])


def test_correctly_specified_model_passes_kupiec(synthetic_returns):
    """On data generated by the model itself the backtest should not reject
    at 95 % over a long out-of-sample span (probability of a false rejection
    is 5 % by construction; the seed is fixed so this is deterministic)."""
    r = synthetic_returns[:2500]
    res = rolling_var_backtest(r, window=750, confidence=(0.95,), refit_every=125, n_paths=4000, seed=1)
    k = res.kupiec[0.95]
    assert 0.03 < k.observed_rate < 0.07
    assert k.passed


def test_no_lookahead(synthetic_returns):
    """VaR on day t must depend only on returns strictly before t."""
    r = synthetic_returns[:700].copy()
    a = rolling_var_backtest(r, window=WINDOW, confidence=(0.95,), refit_every=1, n_paths=1000,
                             seed=5, start=600, end=605)
    r2 = r.copy()
    r2[605:] = 99.0                       # corrupt the future
    r2[603] = -3.0                        # corrupt inside the tested span too
    b = rolling_var_backtest(r2, window=WINDOW, confidence=(0.95,), refit_every=1, n_paths=1000,
                             seed=5, start=600, end=605)
    # days 600..603 see identical history -> identical VaR; day 604 sees r[603] -> differs
    np.testing.assert_allclose(a.var[0.95][:4], b.var[0.95][:4])
    assert a.var[0.95][4] != b.var[0.95][4]


def test_seed_reproducibility(synthetic_returns):
    r = synthetic_returns[:650]
    a = rolling_var_backtest(r, window=WINDOW, refit_every=10, n_paths=500, seed=3)
    b = rolling_var_backtest(r, window=WINDOW, refit_every=10, n_paths=500, seed=3)
    np.testing.assert_array_equal(a.var[0.95], b.var[0.95])


def test_validation(synthetic_returns):
    with pytest.raises(ValueError):
        rolling_var_backtest(synthetic_returns[:300], window=WINDOW)     # nothing out of sample
    with pytest.raises(ValueError):
        rolling_var_backtest(synthetic_returns[:400], window=WINDOW, on_fit_failure="ignore")
    with pytest.raises(ValueError):
        rolling_var_backtest(synthetic_returns[:400], window=WINDOW, refit_every=0)


def test_fit_failure_is_never_silent(monkeypatch, synthetic_returns):
    import cse_risk_engine.backtest as bt_mod
    calls = {"n": 0}
    real_fit = bt_mod.fit_gjr_garch

    def flaky(*a, **k):
        calls["n"] += 1
        if calls["n"] == 2:
            raise ConvergenceError("simulated failure")
        return real_fit(*a, **k)

    monkeypatch.setattr(bt_mod, "fit_gjr_garch", flaky)
    r = synthetic_returns[:340]
    with pytest.raises(ConvergenceError, match="t=310"):
        rolling_var_backtest(r, window=WINDOW, refit_every=10, n_paths=200, seed=0)
    calls["n"] = 0
    with pytest.warns(UserWarning, match="carrying"):
        res = rolling_var_backtest(r, window=WINDOW, refit_every=10, n_paths=200, seed=0, on_fit_failure="carry")
    assert res.failed_fits == (310,)
    assert res.index.size == 40
